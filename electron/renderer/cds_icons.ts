/** Computes the CDS optical font-weight (wght) matching Claude Desktop 4.23118 Os(). */
function opticalWeight(px: number, stroke = 1.25): number {
  const master = px < 18 ? 16 : 20;
  const bounds = WGHT_BOUNDS[master];
  const effective = (stroke * master) / px;
  const ratio = (effective - bounds.lo) / (bounds.hi - bounds.lo);
  const clamped = Math.max(400, Math.min(700, 400 + 300 * ratio));
  return Math.round(clamped * 10) / 10;
}

function codepoint(name: unknown): number | null {
  if (typeof name !== 'string') {
    return null;
  }
  if (!Object.prototype.hasOwnProperty.call(GLYPHS, name)) {
    return null;
  }
  const value = GLYPHS[name];
  return typeof value === 'number' ? value : null;
}

function html(
  name: unknown,
  size: unknown = 'large',
  strong = false
): string {
  const value = codepoint(name);
  if (value === null) {
    return '';
  }
  const sizeKey = typeof size === 'string' && SIZE_SPECS[size] ? size : 'large';
  const spec = SIZE_SPECS[sizeKey];
  const stroke = strong && spec.strong !== undefined ? spec.strong : spec.regular;
  const wght = opticalWeight(spec.px, stroke);
  const axes = typeof name === 'string' ? ANIMATION_AXES[name] : '';
  const weightAttr = strong ? ' data-weight="strong"' : '';
  return `<span class="cds-icon" data-size="${sizeKey}"${weightAttr} style="--cds-wght:${wght};--cds-opsz:${spec.px}"${axes ? ` data-cds-anim="${axes}"` : ''} aria-hidden="true" data-glyph="&#x${value.toString(16).toUpperCase()};"></span>`;
}

function names(): string[] {
  return Object.keys(GLYPHS).sort();
}


import type {HistoryLink, HistoryList} from './resource_browser_history';

export function mergeHistoryLinks(
  rendered: HistoryLink[],
  received: HistoryLink[],
): HistoryLink[] {
  const links = new Map<string, HistoryLink>();
  for (const link of [...rendered, ...received]) {
    if (!links.has(link.id)) {
      links.set(link.id, link);
    }
  }
  return [...links.values()];
}

export function readHistoryResponse(
  value: unknown,
): {links: HistoryLink[]; atEnd: boolean} | null {
  const payload = value as {
    success?: boolean;
    data?: {
      notes?: Array<Record<string, unknown>>;
      note_list?: Array<Record<string, unknown>>;
      has_more?: boolean;
      hasMore?: boolean;
    };
  } | null;
  const data = payload?.data;
  const notes = data?.notes || data?.note_list;
  if (payload?.success === false || !Array.isArray(notes)) {
    return null;
  }
  const links = notes.flatMap(entry => {
    const card = (entry.note_card || entry.noteCard || entry) as Record<
      string,
      unknown
    >;
    const id = String(
      entry.note_id ||
        entry.noteId ||
        entry.id ||
        card.note_id ||
        card.noteId ||
        card.id ||
        '',
    );
    if (!id) {
      return [];
    }
    const token = String(
      entry.xsec_token ||
        entry.xsecToken ||
        card.xsec_token ||
        card.xsecToken ||
        '',
    );
    const user = (card.user || entry.user || {}) as Record<string, unknown>;
    const userId = String(user.user_id || user.userId || '');
    const url = new URL(
      userId
        ? `https://www.xiaohongshu.com/user/profile/${encodeURIComponent(userId)}/${encodeURIComponent(id)}`
        : `https://www.xiaohongshu.com/explore/${encodeURIComponent(id)}`,
    );
    if (token) {
      url.searchParams.set('xsec_token', token);
      url.searchParams.set('xsec_source', 'pc_user');
    }
    return [
      {
        id,
        url: url.href,
        title: String(
          card.display_title ||
            card.displayTitle ||
            card.title ||
            entry.title ||
            '',
        ),
      },
    ];
  });
  return {links, atEnd: data?.has_more === false || data?.hasMore === false};
}

/** Observes only responses generated by this account's normally rendered list. */
export class CollectionHistoryNetwork {
  private readonly requests = new Set<string>();
  private readonly links = new Map<string, HistoryLink>();
  private result: {links: HistoryLink[]; atEnd: boolean} | null = null;
  private attached = false;

  constructor(
    private readonly contents: Electron.WebContents,
    private readonly list: HistoryList,
    private readonly ownerId: string,
  ) {}

  async start(): Promise<void> {
    if (this.contents.debugger.isAttached()) {
      return;
    }
    this.contents.debugger.attach('1.3');
    this.attached = true;
    this.contents.debugger.on('message', this.onMessage);
    await this.contents.debugger.sendCommand('Network.enable');
  }

  snapshot(): {links: HistoryLink[]; atEnd: boolean} | null {
    return this.result;
  }

  stop(): void {
    if (this.attached && !this.contents.isDestroyed()) {
      this.contents.debugger.removeListener('message', this.onMessage);
      if (this.contents.debugger.isAttached()) {
        this.contents.debugger.detach();
      }
    }
  }

  private readonly onMessage = (
    _event: Electron.Event,
    method: string,
    parameters: Record<string, unknown>,
  ): void => {
    if (method === 'Network.responseReceived') {
      const response = parameters.response as {url: string; status: number};
      const url = new URL(response.url);
      const route =
        this.list === 'saved' ? '/note/collect/page' : '/note/like/page';
      if (
        /(^|\.)xiaohongshu\.com$/.test(url.hostname) &&
        url.pathname.endsWith(route) &&
        response.status === 200 &&
        url.searchParams.get('user_id') === this.ownerId
      ) {
        this.requests.add(String(parameters.requestId));
      }
    } else if (
      method === 'Network.loadingFinished' &&
      this.requests.delete(String(parameters.requestId))
    ) {
      void this.contents.debugger
        .sendCommand('Network.getResponseBody', {
          requestId: parameters.requestId,
        })
        .then(response => {
          const body = response.base64Encoded
            ? Buffer.from(response.body, 'base64').toString('utf8')
            : response.body;
          const result = readHistoryResponse(JSON.parse(body));
          if (result) {
            for (const link of result.links) {
              this.links.set(link.id, link);
            }
            this.result = {
              links: [...this.links.values()],
              atEnd: result.atEnd,
            };
          }
        })
        .catch(() => {
          /* DOM scanning remains available if Chromium discards a response body. */
        });
    }
  };
}
